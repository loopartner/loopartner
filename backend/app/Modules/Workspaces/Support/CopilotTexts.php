<?php

namespace App\Modules\Workspaces\Support;

/**
 * Textes du copilote montrés aux utilisateurs (décision 66 ; docs/v1/workspaces-rules.md,
 * section 5, à faire valider par le juriste : points J3 à J5).
 *
 * - notice : information sur l'IA, dont la version doit accompagner chaque génération
 *   (règlement sur l'IA, art. 50 §1 et §5 : information au plus tard à la première
 *   interaction) ;
 * - disclaimer : avertissement joint à chaque réponse du copilote ;
 * - sensitive_data_warning : à afficher près du champ de description (RGPD art. 9).
 *
 * Changer un texte de l'information impose de changer NOTICE_VERSION : l'utilisateur doit
 * relire la nouvelle version avant sa prochaine génération (422 sinon).
 */
final class CopilotTexts
{
    public const NOTICE_VERSION = '2026-11-18';

    public const DISCLAIMER_VERSION = 1;

    public static function notice(string $locale, string $provider): string
    {
        return $locale === 'en'
            ? "The copilot uses an artificial intelligence service ({$provider}, processing in the European Union). When you start a generation, the title and description of your workspace (without email addresses, phone numbers, IBANs, links and company numbers, removed automatically), its country, budget, desired start date, the titles of its steps and your account type are sent to it. Your name, your email address and other users' data are never sent. The result is an automatically generated proposal: review it before applying it."
            : "Le copilote utilise un service d'intelligence artificielle ({$provider}, traitement dans l'Union européenne). Quand vous lancez une génération, le titre et la description de votre workspace (sans les emails, téléphones, IBAN, liens et numéros d'entreprise, retirés automatiquement), son pays, son budget, sa date de début souhaitée, le titre de ses étapes et votre type de compte lui sont envoyés. Votre nom, votre email et les données des autres utilisateurs ne lui sont jamais envoyés. Le résultat est une proposition générée automatiquement : relisez-la avant de l'appliquer.";
    }

    /**
     * @return array{text: string, version: int}
     */
    public static function disclaimer(string $locale): array
    {
        return [
            'text' => $locale === 'en'
                ? 'Content generated by artificial intelligence: it may be incomplete or inaccurate, check it. It is neither legal advice, nor tax advice, nor accounting advice: for these matters, consult a professional (lawyer, chartered accountant).'
                : 'Contenu généré par une intelligence artificielle : il peut être incomplet ou inexact, vérifiez-le. Ce n\'est ni un avis juridique, ni un avis fiscal, ni un conseil comptable : pour ces questions, adressez-vous à un professionnel (avocat, expert-comptable).',
            'version' => self::DISCLAIMER_VERSION,
        ];
    }

    public static function sensitiveDataWarning(string $locale): string
    {
        return $locale === 'en'
            ? 'Do not include health information, political or religious opinions or any other sensitive data, nor anyone\'s contact details: this text may be sent to the copilot\'s AI service.'
            : 'N\'indiquez pas d\'information de santé, d\'opinion politique ou religieuse ni d\'autre donnée sensible, ni les coordonnées d\'une personne : ce texte peut être envoyé au service d\'IA du copilote.';
    }
}
